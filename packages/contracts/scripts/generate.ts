function exampleValue(schema: Schema, key: string): unknown {
  if (schema.anyOf) return exampleValue(schema.anyOf[0]!, key);
  if (schema.$ref) return exampleValue(payload.$defs[schema.$ref.replace('#/$defs/', '')]!, key);
  if (Object.hasOwn(schema, 'const')) return schema.const;
  if (schema.enum) return schema.enum.find(value => value !== null) ?? null;
  const type = Array.isArray(schema.type) ? schema.type.find(item => item !== 'null') ?? 'null' : schema.type;
  switch (type) {
    case 'string': return STRING_VALUES.get(key) ?? key.replaceAll('_', ' ');
    case 'integer': return Math.max(1, Math.trunc(schema.minimum ?? 0));
    case 'number': return Math.max(1.25, schema.minimum ?? 0);
    case 'boolean': return true;
    case 'array': return [exampleValue(schema.items ?? {}, key.replace(/s+$/, ''))];
    case 'object': {
      const fields = Object.entries(schema.properties ?? {});
      if (fields.length) return Object.fromEntries(fields.map(([name, value]) => [name, exampleValue(value, name)]));
      if (key === 'usage') return { input_tokens: 120, output_tokens: 40 };
      if (key === 'pricing') return { cost_usd: 0.0025, status: 'priced' };
      return { value: 'recorded' };
    }
    default: return null;
  }
}


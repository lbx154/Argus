const sortKeys = (value: unknown): unknown => Array.isArray(value) ? value.map(sortKeys)
  : value && typeof value === 'object'
    ? Object.fromEntries(Object.keys(value).sort().map(key => [key, sortKeys((value as Record<string, unknown>)[key])]))
    : value;

function eventCorpus(): string {
  const fixtures = Object.entries(payload.events).map(([type, schema], index) => ({ id: type, event: {
    type, ts: 1_700_000_000 + index, payload_schema_version: schema.version || 1,
    ...Object.fromEntries(Object.entries(schema.properties ?? {}).map(([key, value]) => [key, exampleValue(value, key)])),
    ...EVENT_OVERRIDES[type],
  } }));
  const corpus = { schema_version: 1, event_payload_schema_version: payload.schema_version,
    fixtures: [...fixtures, ...EXTRA_FIXTURES] };
  return `${JSON.stringify(sortKeys(corpus), null, 2)}\n`;
}


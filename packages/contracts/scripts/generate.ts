/** Writes every generated contract artifact from the JSON schemas; dependency-free so bare Node runs it. */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

interface Schema {
  $ref?: string;
  anyOf?: Schema[];
  const?: unknown;
  enum?: unknown[];
  type?: string | string[];
  properties?: Record<string, Schema>;
  required?: string[];
  items?: Schema;
  minimum?: number;
  version?: number;
}

const root = new URL('../../../', import.meta.url);
const readJson = (path: string): unknown => JSON.parse(readFileSync(new URL(path, root), 'utf8'));
const payload = readJson('packages/contracts/schemas/event_payload_schemas.json') as {
  schema_version: number; events: Record<string, Schema>; $defs: Record<string, Schema>;
};
const api = readJson('packages/contracts/schemas/api_protocol.json') as {
  API_SERVICE: string; API_PROTOCOL_NAME: string; API_PROTOCOL_MAJOR: number;
  API_PROTOCOL_MINOR: number; SNAPSHOT_SCHEMA_VERSION: number; API_REQUIRED_CAPABILITIES: string[];
};
const resource = readJson('packages/contracts/schemas/resource_status.json') as Schema & {
  title: string; $defs: Record<string, Schema>;
};

function tsType(schema: Schema, readonly = false): string {
  if (schema.$ref) return schema.$ref.replace('#/$defs/', '');
  if (schema.anyOf) return schema.anyOf.map(variant => tsType(variant, readonly)).join(' | ');
  if (Object.hasOwn(schema, 'const')) return JSON.stringify(schema.const);
  if (schema.enum) return schema.enum.map(value => JSON.stringify(value)).join(' | ');
  if (Array.isArray(schema.type)) return schema.type.map(type => tsType({ ...schema, type }, readonly)).join(' | ');
  switch (schema.type) {
    case 'string': case 'boolean': case 'null': return schema.type;
    case 'integer': case 'number': return 'number';
    case 'array': return `${readonly ? 'ReadonlyArray' : 'Array'}<${tsType(schema.items ?? {}, readonly)}>`;
    case 'object': {
      const keys = Object.keys(schema.properties ?? {});
      if (!keys.length) return 'Record<string, unknown>';
      return `{ ${keys.map(key => field(schema, key, readonly)).join(' ')} }`;
    }
    default: return 'unknown';
  }
}

function field(schema: Schema, key: string, readonly = false): string {
  return `${readonly ? 'readonly ' : ''}${JSON.stringify(key)}${schema.required?.includes(key) ? '' : '?'}: `
    + `${tsType(schema.properties![key]!, readonly)};`;
}

const header = '// Generated by packages/contracts/scripts/generate.ts. Do not edit.';
function eventTypes(): string {
  const lines = [header, "import type { EventMsg } from './events.js';", '',
    `export const EVENT_PAYLOAD_SCHEMA_VERSION = ${payload.schema_version};`, ''];
  for (const [name, schema] of Object.entries(payload.$defs)) lines.push(`export type ${name}Payload = ${tsType(schema).replaceAll(/\b(DeliveryTarget|DeliveryReceipt)\b/g, '$1Payload')};`, '');
  const names = new Map<string, string>();
  for (const [type, schema] of Object.entries(payload.events)) {
    const name = type.split(/[._-]+/).map(part => part[0]?.toUpperCase() + part.slice(1)).join('') + 'Event';
    if ([...names.values()].includes(name)) throw new Error(`duplicate event interface ${name}`);
    names.set(type, name);
    lines.push(`export interface ${name} extends EventMsg {`, `  type: ${JSON.stringify(type)};`,
      `  payload_schema_version?: ${schema.version || 1};`);
    for (const key of Object.keys(schema.properties ?? {})) lines.push(`  ${field(schema, key).replaceAll(/\b(DeliveryTarget|DeliveryReceipt)\b/g, '$1Payload')}`);
    lines.push('}', '');
  }
  lines.push('export interface EventPayloadByType {');
  for (const [type, name] of names) lines.push(`  ${JSON.stringify(type)}: ${name};`);
  lines.push('}', '', 'export type TypedArgusEvent = EventPayloadByType[keyof EventPayloadByType];', '');
  return lines.join('\n');
}

function resourceStatus(): string {
  const interfaceOf = (name: string, schema: Schema) => [`export interface ${name} {`,
    ...Object.keys(schema.properties ?? {}).map(key => `  ${field(schema, key, true)}`), '}', ''];
  return [header, '', ...Object.entries(resource.$defs).flatMap(([name, schema]) => interfaceOf(name, schema)),
    ...interfaceOf(resource.title, resource)].join('\n');
}

// Renderer fixtures: one plausible event per schema, plus the edge cases below.
const artifacts = new Map<string, string>([
  ['packages/contracts/src/eventPayloads.generated.ts', eventTypes()],
  ['frontend/core/src/eventPayloads.generated.ts',
    `${header}\nexport * from '../../../packages/contracts/src/eventPayloads.generated.js';\n`],
  ['packages/contracts/src/apiProtocol.generated.ts', `${header}
export const API_SERVICE = ${JSON.stringify(api.API_SERVICE)};
export const API_PROTOCOL = { name: ${JSON.stringify(api.API_PROTOCOL_NAME)}, major: ${api.API_PROTOCOL_MAJOR}, minServerMinor: ${api.API_PROTOCOL_MINOR} } as const;
export const SNAPSHOT_SCHEMA_VERSION = ${api.SNAPSHOT_SCHEMA_VERSION};
/** What a client may rely on; a server declares API_OPTIONAL_CAPABILITIES only for the features it has. */
export const REQUIRED_API_CAPABILITIES = ${JSON.stringify(api.API_REQUIRED_CAPABILITIES, null, 2)} as const;
`],
  ['frontend/core/src/resourceStatus.generated.ts', resourceStatus()],
]);

const args = process.argv.slice(2);
if (args.length === 0 || (args.length === 1 && args[0] === '--check')) {
  for (const [path, content] of artifacts) {
    const url = new URL(path, root);
    if (args[0] === '--check') {
      let current = '';
      try { current = readFileSync(url, 'utf8'); } catch { /* Missing is stale. */ }
      if (current !== content) {
        process.stderr.write(`Stale contract: ${path}; run npm run contracts:generate\n`);
        process.exitCode = 1;
      }
    } else {
      writeFileSync(fileURLToPath(url), content, 'utf8');
    }
  }
} else {
  throw new Error('usage: generate.ts [--check]');
}

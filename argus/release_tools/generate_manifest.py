#!/usr/bin/env python3
"""Generate the backend/frontend release identity from shipped source."""

from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from argus.release import MANIFEST_SCHEMA_VERSION, source_files  # noqa: E402

MANIFEST_PATH = ROOT / "argus" / "release_manifest.json"
TS_PATH = ROOT / "frontend" / "core" / "src" / "release.generated.ts"


def _head_commit() -> str:
    result = subprocess.run(
        ["git", "-C", str(ROOT), "rev-parse", "HEAD"],
        check=False,
        capture_output=True,
        text=True,
    )
    return result.stdout.strip() if result.returncode == 0 else ""


def _recorded_commit() -> str:
    try:
        return str(json.loads(MANIFEST_PATH.read_text(encoding="utf-8")).get("git_commit") or "")
    except (OSError, ValueError, AttributeError):
        return ""


def _build_commit() -> str:
    """Reuse a source identity across artifact-only commits, never source edits.

    Size-only manifest equality is insufficient: a same-length source edit must
    start a new identity. Git supplies the byte-level changed-path set without
    passing the entire source inventory through Windows' command-line limit.
    """
    head = _head_commit()
    recorded = _recorded_commit()
    if not recorded or recorded == head:
        return head
    try:
        current = MANIFEST_PATH.read_text(encoding="utf-8")
        manifest, _ = render(recorded)
        if current != manifest:
            return head
        ancestor = subprocess.run(
            ["git", "-C", str(ROOT), "merge-base", "--is-ancestor", recorded, head],
            capture_output=True, check=False,
        )
        if ancestor.returncode != 0:
            return head
        changed = subprocess.run(
            ["git", "-C", str(ROOT), "diff", "--name-only", "-z", recorded, "--"],
            capture_output=True, check=False,
        )
        if changed.returncode != 0:
            return head
        paths = {
            path.decode("utf-8", errors="surrogateescape")
            for path in changed.stdout.split(b"\0") if path
        }
        if paths.intersection(json.loads(manifest)["source_files"]):
            return head
    except (OSError, ValueError, KeyError, TypeError):
        return head
    return recorded


def _build_epoch(commit: str) -> int:
    if not commit:
        return 0
    result = subprocess.run(
        ["git", "-C", str(ROOT), "show", "-s", "--format=%ct", commit],
        capture_output=True, text=True, check=False,
    )
    return int(result.stdout.strip()) if result.returncode == 0 and result.stdout.strip().isdigit() else 0


def render(commit: str) -> tuple[str, str]:
    """The manifest and generated TypeScript for a build started at ``commit``."""
    project = tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))
    package_version = os.environ.get("ARGUS_RELEASE_VERSION", "").strip() or str(
        project["project"]["version"]
    )
    release_id = f"{package_version}+{commit[:12]}" if commit else package_version
    manifest = json.dumps(
        {
            "schema_version": MANIFEST_SCHEMA_VERSION,
            "package_version": package_version,
            "git_commit": commit,
            "release_id": release_id,
            "build_epoch": _build_epoch(commit),
            "source_files": source_files(ROOT),
        },
        indent=2,
        sort_keys=True,
    ) + "\n"
    generated = (
        "// Generated by argus.release_tools.generate_manifest. Do not edit.\n"
        f"export const RELEASE_ID = {json.dumps(release_id)};\n"
    )
    return manifest, generated


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true")
    mode.add_argument(
        "--prepare-build",
        action="store_true",
        help=argparse.SUPPRESS,
    )
    args = parser.parse_args(argv)
    if not args.check and not args.prepare_build:
        parser.error(
            "release identity cannot be updated without rebuilding the shipped "
            "frontends; run python -m argus.release_tools.build_release"
        )
    # A build commit sits on top of the commit it was built from, so a check
    # keeps the recorded commit and asks only whether the source still matches.
    manifest, generated = render(_recorded_commit() if args.check else _build_commit())
    if args.check:
        current_manifest = (
            MANIFEST_PATH.read_text(encoding="utf-8") if MANIFEST_PATH.exists() else ""
        )
        current_ts = TS_PATH.read_text(encoding="utf-8") if TS_PATH.exists() else ""
        if current_manifest != manifest or current_ts != generated:
            raise SystemExit(
                "release manifest is stale; run python -m argus.release_tools.build_release"
            )
        return 0
    MANIFEST_PATH.write_text(manifest, encoding="utf-8")
    TS_PATH.write_text(generated, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

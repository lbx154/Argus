def _continuous_objective_from_agents(agents_md: str) -> str:
    for line in agents_md.splitlines():
        if line.startswith("- Primary paper goal: "):
            return line.split(": ", 1)[1]
    return "Start a clean-slate EMNLP/ACL long-paper auto-research project and continue until the L2 reviewer marks `done` against the full pipeline checklist."


def _argus_env() -> dict[str, str]:
    env = os.environ.copy()
    repo_root = Path(__file__).resolve().parents[2]
    existing = env.get("PYTHONPATH")
    env["PYTHONPATH"] = f"{repo_root}{os.pathsep}{existing}" if existing else str(repo_root)
    env.setdefault("ARGUS_SKILL_SOURCE_ROOT", str(repo_root))
    env.setdefault("ARGUS_SKILL_PYTHON", str(_argus_python()))
    return env


def _argus_python() -> Path:
    configured = Path(os.environ.get("ARGUS_SKILL_PYTHON", str(PYTHON))).expanduser()
    if configured.exists():
        return configured
    return Path(sys.executable)


def _interpreter_has_torch(python: Path) -> bool:
    """True when ``python -c 'import torch'`` succeeds for ``python``."""
    try:
        proc = subprocess.run(
            [str(python), "-c", "import torch"],
            capture_output=True,
            timeout=60,
            check=False,
        )
        return proc.returncode == 0
    except (OSError, subprocess.TimeoutExpired):
        return False


def _ml_base_python() -> Path:
    """Pick the base interpreter for a project venv that can ``import torch``.

    On a CUDA host (e.g. Azure ML PyTorch containers) the GPU-enabled torch
    lives in a conda env exposed via ``$CONDA_PREFIX`` — not in the Argus
    framework venv. Building the project venv on that interpreter with
    ``--system-site-packages`` inherits the host CUDA stack so the agent never
    has to download a multi-GB CPU-only torch wheel (or, worse, fake scoring
    because ``import torch`` failed). Preference order:

    1. ``ARGUS_SKILL_ML_PYTHON`` operator override,
    2. ``$CONDA_PREFIX/bin/python`` (the active conda env),
    3. the Argus framework python (fallback — keeps prior behavior when no
       torch-bearing interpreter is found).
    """
    candidates: list[Path] = []
    override = os.environ.get("ARGUS_SKILL_ML_PYTHON", "").strip()
    if override:
        candidates.append(Path(override).expanduser())
    conda_prefix = os.environ.get("CONDA_PREFIX", "").strip()
    if conda_prefix:
        candidates.append(Path(conda_prefix) / "bin" / "python")
    for cand in candidates:
        if cand.exists() and _interpreter_has_torch(cand):
            return cand
    return _argus_python()


def _run(
    cmd: list[str],
    *,
    cwd: Path,
    env: dict[str, str] | None = None,
    timeout: int = 30,
) -> str:
    proc = subprocess.run(
        cmd,
        cwd=cwd,
        env=env,
        text=True,
        capture_output=True,
        timeout=timeout,
        check=False,
    )
    output = (proc.stdout or "") + (proc.stderr or "")
    if proc.returncode != 0:
        rendered = " ".join(cmd)
        raise LaunchError(
            f"command failed with exit {proc.returncode}: {rendered}\n{output.strip()}"
        )
    return output


def _interactive_domain_select() -> str | None:
    """Interactively ask the user to pick a research domain."""
    print("\n🔬 Select a research domain (loads only relevant skills):\n")
    keys = list(AVAILABLE_DOMAINS.keys())
    for i, key in enumerate(keys, 1):
        desc = DOMAIN_DESCRIPTIONS[key]
        print(f"  {i}. {desc}")
    print(f"  {len(keys) + 1}. All domains (load everything — may be slow)")
    print()
    while True:
        try:
            choice = input("Domain [1-{}]: ".format(len(keys) + 1)).strip()
        except (EOFError, KeyboardInterrupt):
            print()
            return None
        if not choice:
            continue
        try:
            idx = int(choice)
        except ValueError:
            # Try matching by name
            if choice.lower() in AVAILABLE_DOMAINS:
                return choice.lower()
            print(f"  Invalid choice. Enter 1-{len(keys) + 1} or a domain name.")
            continue
        if 1 <= idx <= len(keys):
            selected = keys[idx - 1]
            print(f"\n  ✓ Selected: {DOMAIN_DESCRIPTIONS[selected]}\n")
            return selected
        elif idx == len(keys) + 1:
            print("\n  ✓ Loading all domains\n")
            return None
        else:
            print(f"  Invalid choice. Enter 1-{len(keys) + 1}.")



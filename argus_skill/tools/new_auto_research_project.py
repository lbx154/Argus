def _gpu_budget_from_vault() -> str:
    """Render a GPU-allocation clause from the capability vault if available.

    Reads ``~/.argus-skill/capabilities/gpu_resources.json`` via
    :func:`argus_skill.tools.capability_vault.load_gpu_resources` so the
    generated ``AGENTS.md`` automatically reflects the operator's GPU grant
    without forcing the user to retype it on every project.
    """
    try:
        from .capability_vault import load_gpu_resources  # local import to avoid cycle
    except Exception:  # pragma: no cover - defensive
        return ""
    config = load_gpu_resources() or {}
    cuda_vis = str(config.get("cuda_visible_devices") or "").strip()
    if not cuda_vis:
        return ""
    devices = config.get("allowed_devices") or []
    max_mem = config.get("max_gpu_memory_gb")
    parts = [
        f"GPU allocation (from capability vault): ONLY CUDA devices [{cuda_vis}] are available; "
        f"every training/eval/inference command MUST run with CUDA_VISIBLE_DEVICES={cuda_vis} "
        "and MUST NOT touch any other device on the host."
    ]
    if devices:
        parts.append(f"Allowed device indices: {list(devices)}.")
    if max_mem:
        parts.append(f"Aggregate GPU memory budget: ~{max_mem} GB across the allocation.")
    return " ".join(parts)


def _project_venv_clause() -> str:
    """Tell the agent where the project's own virtualenv lives.

    The launcher creates `<project>/.venv` so the agent can pip install
    experiment dependencies without touching the Argus framework venv.
    Without this clause the agent often `pip install`s into whatever
    Python first appears on PATH (which is the Argus venv) and ends up
    polluting the harness with project-specific packages.
    """

    return (
        "Project Python environment: this workspace ships with its own isolated "
        "`./.venv` (created by the launcher). Use `./.venv/bin/python` and "
        "`./.venv/bin/pip` for ALL experiment / dataset / training / inference "
        "code and for any `pip install` of project dependencies. NEVER `pip install` "
        "into the Argus framework Python (the interpreter that runs "
        "`python -m argus_skill.*` / `${ARGUS_SKILL_PYTHON}`) — that interpreter is "
        "reserved exclusively for the argus-skill daemon, reviewer, and helper CLIs. "
        "If a needed package is missing inside `./.venv`, run "
        "`./.venv/bin/pip install <pkg>` from the project root; do not fall back "
        "to system pip or the framework venv."
    )


def default_compute_budget() -> str:
    base = (
        "Use API/model budget only for necessary literature, coding, image-2, review, and "
        "experiment work. Use local GPU capacity for the strongest feasible "
        "domain-appropriate training/adaptation run rather than defaulting to tiny "
        "custom scorers. Stop or ask for operator guidance if a required real benchmark, "
        "model weight/license, GPU capability, or full-scale run is unavailable, or if "
        "repeated repair cycles make no review-relevant progress."
    )
    gpu_clause = _gpu_budget_from_vault()
    venv_clause = _project_venv_clause()
    parts = [p for p in (gpu_clause, venv_clause, base) if p]
    return "\n\n".join(parts)


